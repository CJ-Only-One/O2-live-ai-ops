/**
 * 채팅 화면에 보여줄 닉네임.
 *
 * 프레임에 실리는 `user` 는 세션 키의 HMAC(`u_<16 hex>`)이라 사람이 읽을 것이
 * 못 된다. 예전에는 그 앞 8자를 그대로 닉네임으로 썼는데 화면에 `u_a3f9b2`
 * 같은 문자열이 떴다 — 시청자로 안 보인다.
 *
 * 해시에서 결정론적으로 뽑으므로 **같은 사람은 방송 내내 같은 닉네임**이고,
 * 원본 세션 키는 여전히 어디에도 남지 않는다. 서버가 상태를 들고 있지 않아
 * 파드가 늘거나 재시작해도 닉네임이 바뀌지 않는다.
 *
 * 낱말은 32개다. 뒤에 두 자리 수를 붙여 2,880 가지가 나오므로 한 방송에 수천
 * 명이 들어오면 겹친다 — 화면 표시용이고 신원이 아니므로 그대로 둔다.
 */

const WORDS = [
  '수분충전러', '건성인간', '지성탈출', '민감이', '속건조주의', '보습덕후',
  '세럼모으는중', '토너부자', '올영단골', '피부고민중', '트러블졸업', '광채피부',
  '쿠션러버', '선크림중독', '클렌징장인', '마스크팩요정', '화장대정리중', '뷰티초보',
  '성분덕후', '리뷰정독러', '재구매각', '장바구니헌터', '알뜰쇼핑러', '새벽쇼핑러',
  '겟잇뷰티', '스킨케어러버', '모공관리중', '각질탈출', '주름아가라', '향덕후',
  '민낯자신감', '피부과단골',
];

/** `u_<16 hex>` 에서 낱말과 번호를 뽑는다. 형식이 다르면 앞 8자를 그대로 쓴다. */
export function nicknameFor(userKey: string): string {
  const hex = /^u_([0-9a-f]{16})$/.exec(userKey)?.[1];
  if (!hex) return userKey.slice(0, 8);

  // 앞 8자만 쓰면 그 부분이 같은 키들이 전부 같은 낱말을 받는다. 16자를 두
  // 조각으로 나눠 양쪽을 다 섞는다 — 한쪽만 달라도 낱말과 번호가 같이 바뀐다.
  const hi = parseInt(hex.slice(0, 8), 16);
  const lo = parseInt(hex.slice(8, 16), 16);

  const word = WORDS[((hi ^ lo) >>> 0) % WORDS.length];
  const number = (((hi + lo * 31) >>> 0) % 90) + 10;
  return `${word}${number}`;
}
